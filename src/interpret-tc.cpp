    void write_x(uint32_t guest, tc_lightning_value value) {
        if (guest == 0) {
            failed = true;
            return;
        }
        // Dataflow bookkeeping runs in both passes so discovery and emission
        // fold identically. The old value of this guest dies: memo entries
        // based on it or holding through it go, and if the value written is
        // this instruction's own bare load, the guest becomes its holder
        // (unless the load's base was this same register, whose old value
        // the address used).
        for (auto &m : load_memo) {
            if (m.valid && (m.base == guest || m.holder == guest)) {
                m.valid = false;
            }
        }
        if (pending_load_valid && value.node == pending_load_node && pending_load.base != guest) {
            pending_load.holder = static_cast<uint8_t>(guest);
            load_memo[load_memo_next] = pending_load;
            load_memo_next = (load_memo_next + 1) % std::size(load_memo);
        }
        pending_load_valid = false;
        if (uint64_t computed = 0; eval_node(value.node, computed)) {
            known_mask |= UINT32_C(1) << guest;
            known_const[guest] = computed;
        } else {
            known_mask &= ~(UINT32_C(1) << guest);
        }
        const int8_t slot = map_guest(guest);
        if (discovery || failed) {
            return;
        }
        if (slot == memory_slot) {
            jit_state_t *_jit = jit;
            emit_expression(value.node, scratch_registers[0]);
            jit_stxi(tc_lightning_x_offset + guest * sizeof(uint64_t), TC_JIT_STATE, scratch_registers[0]);
            return;
        }
        emit_expression(value.node, guest_registers[slot]);
    }

    void add_exit(jit_node_t *branch) {
        if (nexits == max_exits) {
            failed = true;
            return;
        }
        const bool loop_body = trace->cycle >= 0 && current >= static_cast<uint32_t>(trace->cycle);
        const uint32_t first = loop_body ? static_cast<uint32_t>(trace->cycle) : 0;
        const uint64_t base_pc = loop_body ? trace->entries[first].vaddr : trace->head;
        auto &link = trace->side[nexits];
        link.successor = trace->entries[current].vaddr;
        link.expected = trace->entries[current].next_pc;
        link.fn = nullptr;
        link.fast_fn = nullptr;
        link.hotcount = tc_online_state::side_hot_reset;
        exits[nexits++] = side_exit{branch, trace->entries[current].vaddr, base_pc, current - first};
    }

    template <typename EXPECTED, typename NOT_EXPECTED>
    static jit_node_t *emit_condition_branch(tc_lightning_execution &e, const tc_lightning_condition &cond,
        bool expected, const EXPECTED &on_expected, const NOT_EXPECTED &on_not_expected) {
        e.emit_expression(cond.lhs, scratch_registers[0], 1);
        e.emit_expression(cond.rhs, scratch_registers[1], 2);
        return expected ? on_expected(scratch_registers[0], scratch_registers[1]) :
                          on_not_expected(scratch_registers[0], scratch_registers[1]);
    }

