#!/usr/bin/env lua5.4
-- Emits the copy-and-patch stencil source (cp-stencils.c) for the backend of
-- copy-patch-rvvm.md.
--
-- The contract is purely positional over the preserve_none argument order
-- (AArch64: x20-x28 then x0-x7, x86-64: r12-r15, rdi, rsi, then more or
-- stack). Parameters are placed so the interpreter's pinned AArch64 roster
-- falls at its own registers: pc at position 4 (x23), countdown at 5 (x24),
-- fetch tag at 6 (x25), context at 8 (x27). Guest-value cache slots fill the
-- remaining positions and every stencil passes all parameters through, so
-- trace entry from a TC handler and exit into the fetch tail are plain
-- branches with no state movement.
--
-- Continuations are musttail calls to extern preserve_none symbols (direct
-- branch relocations, patchable, elidable on fallthrough). 64-bit values are
-- addresses of extern hole arrays: movz/movk chains under the AArch64 large
-- code model, movabs under the x86-64 small model with per-symbol large
-- model (clang) or medium model with sized arrays (GCC).
--
-- Usage: lua5.4 cp-gen-stencils.lua <structural.c> <semantic.cpp>
--
-- The structural TU is C, compiled bare-metal (value holes need ELF's
-- movz/movk relocations). The semantic TU is C++, compiled natively with
-- the host toolchain: it includes interpret.cpp so every instruction
-- stencil instantiates the interpreter's own execute body (single
-- semantic source), and its only relocations are continuation branches,
-- which every object format patches.

local out = assert(arg[1], "usage: cp-gen-stencils.lua <structural.c> <semantic.cpp> [nslots]")
local sem_out = assert(arg[2], "usage: cp-gen-stencils.lua <structural.c> <semantic.cpp> [nslots]")
local f = assert(io.open(out, "w"))

-- Guest cache slot count, per-arch (aarch64 preserve_none has free
-- argument positions through x7, so up to 12; measured demand says 10).
local NSLOTS = tonumber(arg[3]) or 7

local function emit(s) f:write(s, "\n") end

-- Parameter list: position 1 is the state access (the interpreter contract
-- keeps it in x20, and memory stencils consume it directly), positions 4,
-- 5, 6, 8 are the pinned roster, the rest are the seven guest cache slots.
local params_t = {}
local args_t = {}
local slot_param = {"sa", "r0", "r1", "pc", "cd", "fetch", "r2", "tcc"}
for d = 3, NSLOTS - 1 do
    slot_param[#slot_param + 1] = ("r%d"):format(d)
end
for _, name in ipairs(slot_param) do
    params_t[#params_t + 1] = "u64 " .. name
    args_t[#args_t + 1] = name
end
local params = table.concat(params_t, ", ")
local args = table.concat(args_t, ", ")

emit("/* Generated by tools/cp-gen-stencils.lua. Do not edit. */")
emit("")
emit("typedef unsigned long long u64;")
emit("typedef long long i64;")
emit("typedef unsigned int u32;")
emit("typedef int i32;")
emit("typedef __int128 i128;")
emit("typedef unsigned __int128 u128;")
emit("#define CONT __attribute__((preserve_none))")
emit("#define TAIL __attribute__((musttail))")
emit("")
emit("/* Continuation holes (patched to branch targets). */")
emit(("CONT extern void cp_cont_0(%s);"):format(params))
emit(("CONT extern void cp_cont_1(%s);"):format(params))
emit("/* 64-bit value holes. */")
emit("#if defined(__x86_64__) && defined(__clang__)")
emit("#define CP_HOLE __attribute__((model(\"large\")))")
emit("#else")
emit("#define CP_HOLE")
emit("#endif")
emit("/* Sized so GCC's medium model (-mlarge-data-threshold) makes them")
emit(" * large data, reached by movabs with R_X86_64_64. */")
emit("CP_HOLE extern char cp_imm64_0[65536];")
emit("CP_HOLE extern char cp_imm64_1[65536];")
emit("CP_HOLE extern char cp_imm64_2[65536];")
emit("CP_HOLE extern char cp_imm64_3[65536];")
emit("")

local function fn(name, body)
    emit(("CONT void %s(%s)"):format(name, params))
    emit("{")
    emit(body)
    emit("    TAIL return cp_cont_0(" .. args .. ");")
    emit("}")
    emit("")
end

-- Terminal stencil for the tests: store every parameter through a patched
-- pointer and return to the (ordinary, caller-saves-everything) host caller.
emit(("CONT void cp_store_exit(%s)"):format(params))
emit("{")
emit("    u64 *o = (u64 *)cp_imm64_0;")
for i, name in ipairs(slot_param) do
    emit(("    o[%d] = %s;"):format(i - 1, name))
end
emit("}")
emit("")

-- Trace entry tick guard: the trace body fits before the tick end only when
-- the countdown exceeds the trace's worst-case pending count (a patched
-- constant). Signed compare: the privileged path can drive the countdown
-- negative. Bail is continuation 1, the body is the elidable fallthrough.
emit(("CONT void cp_tick_guard(%s)"):format(params))
emit("{")
emit("    if ((i64)cd <= (i64)(u64)cp_imm64_0) {")
emit("        TAIL return cp_cont_1(" .. args .. ");")
emit("    }")
emit("    TAIL return cp_cont_0(" .. args .. ");")
emit("}")
emit("")

-- Side exit: move the fast pc by a signed delta from the trace head
-- (the typed fast pc is position-encoded, so exits add displacements,
-- never absolute values), charge the pending instruction count against
-- the countdown, and leave for the fetch-tail continuation.
emit(("CONT void cp_exit_stub(%s)"):format(params))
emit("{")
emit("    pc += (u64)cp_imm64_0;")
emit("    cd -= (u64)cp_imm64_1;")
emit("    TAIL return cp_cont_0(" .. args .. ");")
emit("}")
emit("")

-- Compare a 64-bit field at a patched address against a patched constant,
-- bailing on mismatch. The call-entry prologue validates the translation
-- context and the hot code-TLB slot with these; the bail leaves with the
-- caller's deposit pc untouched, so misses resume the ordinary fetch path.
emit(("CONT void cp_cmp_mem_imm(%s)"):format(params))
emit("{")
emit("    if (*(u64 *)cp_imm64_0 != (u64)cp_imm64_1) {")
emit("        TAIL return cp_cont_1(" .. args .. ");")
emit("    }")
emit("    TAIL return cp_cont_0(" .. args .. ");")
emit("}")
emit("")

-- Copy a 64-bit field between two patched addresses (the entry-time
-- pma_index publish, read from the shadow slot).
emit(("CONT void cp_copy_mem(%s)"):format(params))
emit("{")
emit("    *(u64 *)cp_imm64_1 = *(u64 *)cp_imm64_0;")
emit("    TAIL return cp_cont_0(" .. args .. ");")
emit("}")
emit("")

-- Bail-path counter: bump a 64-bit counter through a patched address.
-- Emitted only on cold paths (the per-cause counting islands), so the
-- statistics cost nothing on hot paths.
emit(("CONT void cp_count(%s)"):format(params))
emit("{")
emit("    ++*(u64 *)cp_imm64_0;")
emit("    TAIL return cp_cont_0(" .. args .. ");")
emit("}")
emit("")

-- Fused call prologue, stencil one: probe the hot code-TLB slot of the
-- CURRENT translation context (exactly the interpreter's own per-transit
-- fetch probe, so hits and misses reproduce its hashed fill sequence;
-- content identity comes from the vh compare), then establish: pc derives
-- from the incoming deposit (vpc + caller vf, the universal entry
-- convention) without a hole, the fetch register and penumbra vf publish
-- the recorded mapping, and the computed slot index rides to stencil two
-- in slot r0 (dead at entry). Holes: 0 hot-set base, 1 head page, 2
-- recorded vf, 3 the tlb_ctx_slot_base address. Layout facts baked as
-- literals (slot sizes, the vf-next-to-ctx adjacency, the tcc field
-- offsets) are pinned by static_asserts in interpret-cp.inc.
local TCC_FETCH_PAGE_OFF = 32
local TCC_PMA_OFF = 40
emit(("CONT void cp_call_probe(%s)"):format(params))
emit("{")
emit("    u64 idx = (((u64)cp_imm64_1) >> 12) & 255;")
emit("    u64 ctxb = *(u64 *)cp_imm64_3;")
emit("    u64 *slot = (u64 *)((u64)cp_imm64_0 + (ctxb + idx) * 16);")
emit("    if (slot[0] != (u64)cp_imm64_1 || slot[1] != (u64)cp_imm64_2) {")
emit("        TAIL return cp_cont_1(" .. args .. ");")
emit("    }")
emit("    u64 caller_vf = *(u64 *)((u64)cp_imm64_3 - 8);")
emit("    pc = pc - caller_vf + (u64)cp_imm64_2;")
emit("    *(u64 *)((u64)cp_imm64_3 - 8) = (u64)cp_imm64_2;")
emit("    fetch = (u64)cp_imm64_1 + (u64)cp_imm64_2;")
emit(("    *(u64 *)(tcc + %d) = fetch;"):format(TCC_FETCH_PAGE_OFF))
emit("    r0 = ctxb + idx;")
emit("    TAIL return cp_cont_0(" .. args .. ");")
emit("}")
emit("")
-- Stencil two: the entry-time pma publish from the shadow slot of the
-- same (current-context) index, delivered in r0. Hole: 0 shadow-set base.
emit(("CONT void cp_call_pma(%s)"):format(params))
emit("{")
emit("    u64 pma = *(u64 *)((u64)cp_imm64_0 + r0 * 32 + 16);")
emit(("    *(u64 *)(tcc + %d) = pma;"):format(TCC_PMA_OFF))
emit("    TAIL return cp_cont_0(" .. args .. ");")
emit("}")
emit("")

-- Store a patched constant through a patched address. The call-entry
-- prologue publishes the established fetch-mapping fields with these,
-- before the register re-encode, with no C boundary in between.
emit(("CONT void cp_store_imm(%s)"):format(params))
emit("{")
emit("    *(u64 *)cp_imm64_0 = (u64)cp_imm64_1;")
emit("    TAIL return cp_cont_0(" .. args .. ");")
emit("}")
emit("")

-- Call-entry establishment: re-encode the pinned pc and fetch registers to
-- the trace's recorded mapping. Both are install-time constants because the
-- hook only enters when the hot slot's vh_offset equals the recorded
-- code_vf_offset. Falls through into the tick guard.
emit(("CONT void cp_call_establish(%s)"):format(params))
emit("{")
emit("    pc = (u64)cp_imm64_0;")
emit("    fetch = (u64)cp_imm64_1;")
emit("    TAIL return cp_cont_0(" .. args .. ");")
emit("}")
emit("")

-- li: slot d = constant.
for d = 0, NSLOTS - 1 do
    fn(("cp_li_%d"):format(d), ("    r%d = (u64)cp_imm64_0;"):format(d))
end

-- Far jump: tail call through a 64-bit hole, the per-heap island through
-- which exits reach the interpreter continuation beyond direct branch
-- range. No runtime assembler: the indirect branch is compiler-emitted.
emit(("typedef CONT void (*cp_cont_t)(%s);"):format(params))
emit(("CONT void cp_far_jump(%s)"):format(params))
emit("{")
emit("    /* Two-hole sum defeats the direct-branch fold: the compiler")
emit("     * cannot resolve sym+sym to one target, so it materializes and")
emit("     * branches through a register. Patched as target plus zero. */")
emit("    TAIL return ((cp_cont_t)((u64)cp_imm64_0 + (u64)cp_imm64_1))(" .. args .. ");")
emit("}")
emit("")

-- Dynamic-exit deposit: re-encode the pinned pc as the interpreter's own
-- convention for an indirect target, vaddr plus the current segment's
-- fetch_vf_offset (loaded through the patched address). Runs after the
-- countdown charge, before the lookup: both the chain hit and every miss
-- or bail leave with this exact deposit, as execute_jump would.
for d = 0, NSLOTS - 1 do
    fn(("cp_deposit_pc_%d"):format(d), ("    pc = r%d + *(u64 *)cp_imm64_0;"):format(d))
end

-- Lookup tail (RVVM jtlb probe): direct-mapped front cache of
-- {guest vpc, self-validating call entry} pairs, indexed (v >> 1) & mask.
-- A hit chains straight into the entry (which validates and, on any
-- mismatch, bails to the island with the deposit pc); a miss leaves for
-- the island. The cold paths all stay behind exits.
for d = 0, NSLOTS - 1 do
    emit(("CONT void cp_lookup_%d(%s)"):format(d, params))
    emit("{")
    emit(("    u64 v = r%d;"):format(d))
    emit("    u64 *e = (u64 *)((u64)cp_imm64_0 + (((v >> 1) & 255) << 4));")
    emit("    if (e[0] == v) {")
    emit("        TAIL return ((cp_cont_t)e[1])(" .. args .. ");")
    emit("    }")
    emit("    TAIL return cp_cont_0(" .. args .. ");")
    emit("}")
    emit("")
end

f:close()

