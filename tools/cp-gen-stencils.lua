#!/usr/bin/env lua5.4
-- Emits the copy-and-patch stencil source (cp-stencils.c) for the AArch64
-- backend of copy-patch-rvvm.md.
--
-- The stencil contract is the preserve_none AArch64 argument order: the
-- first eight u64 parameters land in x20-x27 and are the guest-value cache
-- slots; every stencil passes all eight through so live values stay in
-- registers across stencil boundaries. Continuations are musttail calls to
-- extern preserve_none symbols (bare B + R_AARCH64_JUMP26, patchable and
-- elidable on fallthrough). 64-bit values are addresses of extern arrays
-- under -mcmodel=large (movz/movk chain, R_AARCH64_MOVW_UABS_G0_NC..G3).
--
-- Usage: lua5.4 cp-gen-stencils.lua <output.c>

local out = assert(arg[1], "usage: cp-gen-stencils.lua <output.c>")
local f = assert(io.open(out, "w"))

local NSLOTS = 8

local function emit(s) f:write(s, "\n") end

emit("/* Generated by tools/cp-gen-stencils.lua. Do not edit. */")
emit("")
emit("typedef unsigned long long u64;")
emit("#define CONT __attribute__((preserve_none))")
emit("#define TAIL __attribute__((musttail))")
emit("")
emit("/* Continuation holes (patched to B targets). */")
emit("CONT extern void cp_cont_0(u64, u64, u64, u64, u64, u64, u64, u64);")
emit("CONT extern void cp_cont_1(u64, u64, u64, u64, u64, u64, u64, u64);")
emit("/* 64-bit value holes. On AArch64 the large code model turns these into")
emit(" * movz/movk chains; on x86-64 the per-symbol large model yields movabs")
emit(" * with R_X86_64_64 while continuations stay direct rel32 jumps. */")
emit("#if defined(__x86_64__) && defined(__clang__)")
emit("#define CP_HOLE __attribute__((model(\"large\")))")
emit("#else")
emit("#define CP_HOLE")
emit("#endif")
emit("/* Sized so GCC's medium model (-mlarge-data-threshold) makes them")
emit(" * large data, reached by movabs with R_X86_64_64. */")
emit("CP_HOLE extern char cp_imm64_0[65536];")
emit("CP_HOLE extern char cp_imm64_1[65536];")
emit("")

local slots = {}
for i = 0, NSLOTS - 1 do
    slots[#slots + 1] = "r" .. i
end
local params = "u64 " .. table.concat(slots, ", u64 ")
local args = table.concat(slots, ", ")

local function fn(name, body)
    emit(("CONT void %s(%s)"):format(name, params))
    emit("{")
    emit(body)
    emit("    TAIL return cp_cont_0(" .. args .. ");")
    emit("}")
    emit("")
end

-- Terminal stencil: store the eight slots through a patched pointer and
-- return to the (ordinary, caller-saves-everything) host caller.
emit(("CONT void cp_store_exit(%s)"):format(params))
emit("{")
emit("    u64 *o = (u64 *)cp_imm64_0;")
for i = 0, NSLOTS - 1 do
    emit(("    o[%d] = r%d;"):format(i, i))
end
emit("}")
emit("")

-- li: slot d = constant.
for d = 0, NSLOTS - 1 do
    fn(("cp_li_%d"):format(d), ("    r%d = (u64)cp_imm64_0;"):format(d))
end

-- add: slot d = slot s1 + slot s2, full placement enumeration.
for d = 0, NSLOTS - 1 do
    for s1 = 0, NSLOTS - 1 do
        for s2 = 0, NSLOTS - 1 do
            fn(("cp_add_%d_%d_%d"):format(d, s1, s2), ("    r%d = r%d + r%d;"):format(d, s1, s2))
        end
    end
end

-- addi: slot d = slot s + 64-bit constant.
for d = 0, NSLOTS - 1 do
    for s = 0, NSLOTS - 1 do
        fn(("cp_addi_%d_%d"):format(d, s), ("    r%d = r%d + (u64)cp_imm64_0;"):format(d, s))
    end
end

-- beq guard: taken continuation 0, fallthrough continuation 1.
for s1 = 0, NSLOTS - 1 do
    for s2 = 0, NSLOTS - 1 do
        emit(("CONT void cp_beq_%d_%d(%s)"):format(s1, s2, params))
        emit("{")
        emit(("    if (r%d == r%d) {"):format(s1, s2))
        emit("        TAIL return cp_cont_0(" .. args .. ");")
        emit("    }")
        emit("    TAIL return cp_cont_1(" .. args .. ");")
        emit("}")
        emit("")
    end
end

-- ld: slot d = *(u64 *)(slot s + constant). Memory-shape probe; the real
-- hot TLB family replaces this in the backend integration.
for d = 0, NSLOTS - 1 do
    for s = 0, NSLOTS - 1 do
        fn(("cp_ld_%d_%d"):format(d, s), ("    r%d = *(const u64 *)(r%d + (u64)cp_imm64_0);"):format(d, s))
    end
end

f:close()
